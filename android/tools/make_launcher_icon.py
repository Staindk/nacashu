# Usage: python3 make_launcher_icon.py
# Draws docs/icon.png (the 32x32 app icon) as the companion app's adaptive launcher icon:
# res/drawable/ic_launcher_foreground.xml and ic_launcher_monochrome.xml, one square per pixel.
# White pixels are the watch, #555555 pixels are the straps, black is the background. Needs Pillow.
#
# Nothing runs this automatically. After changing docs/icon.png, run it by hand and commit the
# regenerated drawables with it. The watchapp's 25x25 menu icon is hand-drawn and isn't made here.
import os
from PIL import Image

ROOT = os.path.join(os.path.dirname(__file__), "..", "..")
WATCH, STRAP = (255, 255, 255), (85, 85, 85)

icon = Image.open(os.path.join(ROOT, "docs", "icon.png")).convert("RGB")
assert icon.size == (32, 32), icon.size
for colour in icon.getcolors():
    assert colour[1] in (WATCH, STRAP, (0, 0, 0)), f"unexpected colour {colour[1]}"


def path_data(colour):
    """One rectangle per run of same-coloured pixels in a row."""
    runs = []
    for y in range(32):
        x = 0
        while x < 32:
            if icon.getpixel((x, y)) != colour:
                x += 1
                continue
            start = x
            while x < 32 and icon.getpixel((x, y)) == colour:
                x += 1
            runs.append(f"M{start},{y}h{x - start}v1h-{x - start}z")
    return "".join(runs)


HEADER = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by android/tools/make_launcher_icon.py from docs/icon.png. Don't edit by hand.
     {comment} -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="48"
    android:viewportHeight="48">
    <group
        android:translateX="8"
        android:translateY="8">
"""
FOOTER = """    </group>
</vector>
"""


def path(fill, data, alpha=None):
    alpha_attr = f'\n            android:fillAlpha="{alpha}"' if alpha else ""
    return f"""        <path
            android:fillColor="{fill}"{alpha_attr}
            android:pathData="{data}" />
"""


watch, strap = path_data(WATCH), path_data(STRAP)
drawables = {
    "ic_launcher_foreground.xml": (
        "The 32x32 pixel icon, one square per pixel. The 108dp\n"
        "     adaptive icon canvas maps to 48 units, so the 32 pixels fill the 72dp safe zone.",
        path("#FFFFFF", watch) + path("#555555", strap),
    ),
    "ic_launcher_monochrome.xml": (
        "Android 13+ themed icon: ic_launcher_foreground in one colour, with the straps\n"
        "     at 40% so they still read as straps.",
        path("#FFFFFF", watch) + path("#FFFFFF", strap, alpha="0.4"),
    ),
}

out = os.path.join(ROOT, "android", "app", "src", "main", "res", "drawable")
for name, (comment, paths) in drawables.items():
    with open(os.path.join(out, name), "w") as f:
        f.write(HEADER.format(comment=comment) + paths + FOOTER)
    print("wrote", name)
