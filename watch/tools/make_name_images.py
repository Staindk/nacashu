# Usage: python3 make_name_images.py /path/to/Silkscreen-Bold.ttf (Silkscreen-Regular.ttf beside it)
# Draws the app name as a white spine along the screen edge, one size per screen. The Pebble
# SDK can't draw rotated text, so the name ships as small images. Also writes the companion app's
# header (android/app/src/main/res/drawable/header.xml). Needs Pillow.
# Silkscreen is under the SIL Open Font License: https://fonts.google.com/specimen/Silkscreen
#
# Nothing runs this automatically: the build and CI use the PNGs committed in resources/images.
# After changing this script, run it by hand and commit the regenerated images and header with it.
import os, sys
from PIL import Image, ImageDraw, ImageFont

NAME = "NACASHU"
# Screen: (screen height, spine width, pixel scale, letter gap, text offset from the inner edge).
# A scale of (2, 3) makes each font pixel 2 wide along the spine and 3 tall across it.
# On the round screen the spine runs past the curve, so the offset sets how far out the text sits.
SCREENS = {
    "large": (228, 28, (3, 4), 4, None),
    "small": (168, 22, (2, 3), 4, None),
    "round": (260, 46, (2, 4), 4, 5),
}

font = ImageFont.truetype(sys.argv[1], 8)  # Silkscreen's native pixel size
letters = []
for ch in NAME:
    img = Image.new("1", (16, 16), 0)
    ImageDraw.Draw(img).text((2, 2), ch, font=font, fill=1)
    letters.append(img.crop(img.getbbox()))

out = os.path.join(os.path.dirname(__file__), "..", "resources", "images")
os.makedirs(out, exist_ok=True)
for screen, (length, width, scale, gap, offset) in SCREENS.items():
    h = max(l.height for l in letters)
    text = Image.new("1", (sum(l.width for l in letters) + gap * (len(letters) - 1), h), 0)
    x = 0
    for l in letters:
        text.paste(l, (x, h - l.height))
        x += l.width + gap
    sx, sy = scale
    text = text.resize((text.width * sx, text.height * sy), Image.NEAREST)
    spine = Image.new("1", (length, width), 1)
    y = (width - text.height) // 2 if offset is None else offset
    spine.paste(0, ((length - text.width) // 2, y), text)
    # Reads top to bottom on the left edge and bottom to top on the right, so it's upright when
    # you tilt the watch towards you: left wrist with lefty off, right wrist with lefty on.
    spine.rotate(-90, expand=True).save(os.path.join(out, f"name_down_{screen}.png"))
    spine.rotate(90, expand=True).save(os.path.join(out, f"name_up_{screen}.png"))

# The companion app's header: the same pixel font as one vector drawable, so the app ships no font
# files. Each line's pixels become squares in one path, coloured by the theme's text colour.
# (lines: text, Silkscreen weight, font pixel size in quarter-dp, gap above in quarter-dp, alpha)
HEADER = [("NACASHU", "Bold", 14, 0, 1.0), ("NATIVE CAMERA SHUTTER", "Regular", 8, 32, 1.0),
          ("FOR PEBBLE", "Regular", 7, 24, 0.7)]


def line_path(text, ttf, scale, top):
    font = ImageFont.truetype(ttf, 8)
    img = Image.new("1", (8 * len(text) + 8, 16), 0)
    ImageDraw.Draw(img).text((0, 2), text, font=font, fill=1)
    left, upper, right, lower = img.getbbox()
    img = img.crop((left, upper, right, lower))
    # One rectangle per horizontal run of lit pixels keeps the path short.
    cmds = []
    for y in range(img.height):
        x = 0
        while x < img.width:
            if img.getpixel((x, y)):
                start = x
                while x < img.width and img.getpixel((x, y)):
                    x += 1
                cmds.append(f"M{start * scale},{top + y * scale}h{(x - start) * scale}v{scale}h{(start - x) * scale}z")
            x += 1
    return "".join(cmds), img.width * scale, top + img.height * scale


ttf_dir = os.path.dirname(sys.argv[1])
paths, width, top = [], 0, 0
for text, weight, scale, gap, alpha in HEADER:
    data, w, top = line_path(text, os.path.join(ttf_dir, f"Silkscreen-{weight}.ttf"), scale, top + gap)
    paths.append((data, alpha))
    width = max(width, w)
xml = ['<?xml version="1.0" encoding="utf-8"?>',
       "<!-- Generated by watch/tools/make_name_images.py: Silkscreen pixel text, SIL Open Font License. -->",
       '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
       f'    android:width="{width / 4}dp" android:height="{top / 4}dp"',
       f'    android:viewportWidth="{width}" android:viewportHeight="{top}">']
for data, alpha in paths:
    xml.append(f'    <path android:fillColor="?android:attr/textColorPrimary" android:fillAlpha="{alpha}"')
    xml.append(f'        android:pathData="{data}" />')
xml.append("</vector>")
header = os.path.join(os.path.dirname(__file__), "..", "..", "android", "app", "src", "main", "res", "drawable", "header.xml")
with open(header, "w") as f:
    f.write("\n".join(xml) + "\n")
